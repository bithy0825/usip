auto make_color_lut(colormap_type type, bool zero_is_black) -> color_lut
{
    color_lut lut;
    lut.type = type;
    lut.zero_is_black = zero_is_black;
    lut.entries = base_words(type);
    if (zero_is_black)
        lut.entries[0] = 0xFF000000u; // 域零(灰度 0)固定纯黑,烘焙零分支
    return lut;
}

auto make_diff_lut(colormap_type type, bool zero_is_black) -> diff_lut
{
    const auto base = base_words(type);

    diff_lut lut;
    lut.type = type;
    lut.zero_is_black = zero_is_black;
    for (auto [k, word] : std::views::enumerate(lut.entries)) {
        // k = d+255 ∈ [0,510];p = k×255/510,偶数 k 落整数位(奇数差值精确取
        // 表项),奇数 k 落半格(相邻项精确中点)
        const auto p = static_cast<double>(k) * (255.0 / 510.0);
        const auto i0 = std::min(static_cast<std::size_t>(p), std::size_t { 254 });
        const auto f = p - static_cast<double>(i0);

        const auto c0 = base[i0];
        const auto c1 = base[i0 + 1];
        const auto mix = [f](unsigned s0, unsigned s1) {
            // lerp 在 double 域内插值:unsigned 直接相减会在降通道下溢;
            // t=0/1 时精确返回端点
            return static_cast<std::uint32_t>(
                std::lround(std::lerp(static_cast<double>(s0), static_cast<double>(s1), f)));
        };
        const auto r = mix(c0 & 0xFFu, c1 & 0xFFu);
        const auto g = mix((c0 >> 8) & 0xFFu, (c1 >> 8) & 0xFFu);
        const auto b = mix((c0 >> 16) & 0xFFu, (c1 >> 16) & 0xFFu);
        word = 0xFF000000u | (b << 16) | (g << 8) | r;
    }
    if (zero_is_black)
        lut.entries[255] = 0xFF000000u; // 域零(零差异,k=255)固定纯黑
    return lut;
}

auto colorize(const QImage& gray, const color_lut& lut,
    std::optional<std::pair<double, double>> range16) -> QImage
{
    if (!pseudocolorable(gray.format())) {
        common::log_warn("pseudocolor rejected: image format {} is not grayscale",
            static_cast<int>(gray.format()));
        return { };
    }

    QImage out { gray.size(), QImage::Format_RGBA8888 };
    if (out.isNull()) // 尺寸过大分配失败
        return { };
    out.setDevicePixelRatio(gray.devicePixelRatio());

    const auto* lut_ptr = lut.entries.data();
    if (gray.format() == QImage::Format_Grayscale8) {
        apply_lut_u8(gray.constBits(), gray.bytesPerLine(),
            reinterpret_cast<std::uint32_t*>(out.bits()),
            out.bytesPerLine() / 4, gray.width(), gray.height(), lut_ptr);
    } else {
        auto [lo, hi] = range16.value_or(std::pair { 0.0, 65535.0 });
        if (!(hi > lo))
            hi = lo + 1.0; // 退化量程(hist min==max 等):全部落索引 0
        apply_lut_u16(reinterpret_cast<const std::uint16_t*>(gray.constBits()),
            gray.bytesPerLine() / 2,
            reinterpret_cast<std::uint32_t*>(out.bits()),
            out.bytesPerLine() / 4, gray.width(), gray.height(), lo, hi, lut_ptr);
    }
    return out;
}

auto colorize_diff(const QImage& diff, const diff_lut& lut) -> QImage
{
    if (diff.format() != QImage::Format_Grayscale16) {
        common::log_warn("diff pseudocolor rejected: image format {} is not grayscale16",
            static_cast<int>(diff.format()));
        return { };
    }

    QImage out { diff.size(), QImage::Format_RGBA8888 };
    if (out.isNull()) // 尺寸过大分配失败
        return { };
    out.setDevicePixelRatio(diff.devicePixelRatio());

    apply_diff_lut_u16(reinterpret_cast<const std::uint16_t*>(diff.constBits()),
        diff.bytesPerLine() / 2,
        reinterpret_cast<std::uint32_t*>(out.bits()),
        out.bytesPerLine() / 4, diff.width(), diff.height(), lut.entries.data());
    return out;
}

