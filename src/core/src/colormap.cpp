    // ─── SIMD 内核 ─────────────────────────────────────────────────────────

    // 8 位索引 → RGBA:逐行 LoadU u8 → 加宽 i32 → GatherIndex 查 LUT → StoreU
    void apply_lut_u8(const std::uint8_t* src, std::ptrdiff_t src_stride,
        std::uint32_t* dst, std::ptrdiff_t dst_stride, int width, int height,
        const std::uint32_t* lut)
    {
        const hn::ScalableTag<std::uint32_t> d32;
        const hn::RebindToSigned<decltype(d32)> di; // GatherIndex 的索引通道
        const hn::Rebind<std::uint16_t, decltype(di)> d16;
        const hn::Rebind<std::uint8_t, decltype(d16)> d8;
        const std::size_t n = hn::Lanes(d32);

        for (int y = 0; y < height; ++y) {
            const auto* row = src + static_cast<std::size_t>(y) * src_stride;
            auto* out = dst + static_cast<std::size_t>(y) * dst_stride;
            std::size_t x = 0;
            for (; x + n <= static_cast<std::size_t>(width); x += n) {
                const auto idx = hn::PromoteTo(di,
                    hn::PromoteTo(d16, hn::LoadU(d8, row + x)));
                hn::StoreU(hn::GatherIndex(d32, lut, idx), d32, out + x);
            }
            for (; x < static_cast<std::size_t>(width); ++x)
                out[x] = lut[row[x]];
        }
    }

    // 16 位索引 → RGBA:一遍完成归一化与查表,不落中间缓冲。
    // 索引 = clamp((v − lo) × 255/(hi − lo)),round-to-nearest-even(与尾段一致)
    void apply_lut_u16(const std::uint16_t* src, std::ptrdiff_t src_stride,
        std::uint32_t* dst, std::ptrdiff_t dst_stride, int width, int height,
        double lo, double hi, const std::uint32_t* lut)
    {
        const auto lof = static_cast<float>(lo);
        const auto scale = static_cast<float>(255.0 / (hi - lo));

        const hn::ScalableTag<float> df;
        const hn::RebindToUnsigned<decltype(df)> du; // u32 与 f32 同宽,GatherIndex 用
        const hn::RebindToSigned<decltype(df)> di; // i32 索引通道
        const hn::Rebind<std::uint16_t, decltype(du)> d16;
        const std::size_t n = hn::Lanes(df);
        const auto vlo = hn::Set(df, lof);
        const auto vscale = hn::Set(df, scale);
        const auto zero = hn::Zero(df);
        const auto vmax = hn::Set(df, 255.0f);

        for (int y = 0; y < height; ++y) {
            const auto* row = src + static_cast<std::size_t>(y) * src_stride;
            auto* out = dst + static_cast<std::size_t>(y) * dst_stride;
            std::size_t x = 0;
            for (; x + n <= static_cast<std::size_t>(width); x += n) {
                const auto v = hn::ConvertTo(df, hn::PromoteTo(du, hn::LoadU(d16, row + x)));
                auto f = hn::Mul(hn::Sub(v, vlo), vscale);
                f = hn::Clamp(f, zero, vmax);
                const auto idx = hn::ConvertTo(di, hn::Round(f));
                hn::StoreU(hn::GatherIndex(du, lut, idx), du, out + x);
            }
            for (; x < static_cast<std::size_t>(width); ++x) {
                const auto f = std::clamp((static_cast<float>(row[x]) - lof) * scale, 0.0f, 255.0f);
                out[x] = lut[static_cast<unsigned>(std::nearbyint(f))];
            }
        }
    }

    // 差值索引 → RGBA:u16 偏移编码(k = d+255)直接查 511 项表,无归一化;
    // 索引 Min-clamp 到 510,防脏值越界 gather
    void apply_diff_lut_u16(const std::uint16_t* src, std::ptrdiff_t src_stride,
        std::uint32_t* dst, std::ptrdiff_t dst_stride, int width, int height,
        const std::uint32_t* lut)
    {
        const hn::ScalableTag<std::uint32_t> d32;
        const hn::RebindToSigned<decltype(d32)> di; // GatherIndex 的索引通道
        const hn::Rebind<std::uint16_t, decltype(di)> d16;
        const std::size_t n = hn::Lanes(d32);
        const auto vmax = hn::Set(di, 510);

        for (int y = 0; y < height; ++y) {
            const auto* row = src + static_cast<std::size_t>(y) * src_stride;
            auto* out = dst + static_cast<std::size_t>(y) * dst_stride;
            std::size_t x = 0;
            for (; x + n <= static_cast<std::size_t>(width); x += n) {
                const auto idx = hn::Min(hn::PromoteTo(di, hn::LoadU(d16, row + x)), vmax);
                hn::StoreU(hn::GatherIndex(d32, lut, idx), d32, out + x);
            }
            for (; x < static_cast<std::size_t>(width); ++x)
                out[x] = lut[std::min(row[x], std::uint16_t { 510 })];
        }
    }

    // ─── LUT 装配 ─────────────────────────────────────────────────────────

    [[nodiscard]] const rgb_table* table_of(colormap_type type)
    {
        switch (type) {
        case colormap_type::jet:
            return &jet_table;
        case colormap_type::parula:
            return &parula_table;
        case colormap_type::viridis:
            return &viridis_table;
        case colormap_type::plasma:
            return &plasma_table;
        }
        std::unreachable();
    }

    // 基础 256 项 RGBA8888 内存字(不含 zero_is_black 烘焙;两表共用)
    [[nodiscard]] auto base_words(colormap_type type) -> std::array<std::uint32_t, 256>
    {
        std::array<std::uint32_t, 256> words {};
        for (const auto [i, rgb] : std::views::enumerate(*table_of(type)))
            // RGBA8888 内存字(小端):r | g<<8 | b<<16 | 0xFF<<24,直写 scanLine
            words[static_cast<std::size_t>(i)] = 0xFF000000u
                | (std::uint32_t { rgb[2] } << 16) | (std::uint32_t { rgb[1] } << 8)
                | std::uint32_t { rgb[0] };
        return words;
    }

